// Procedural Nemesis Rival Generator helper
export function generateRandomNemesis(
  position: number,
  rankTier: 'overlord' | 'warlord' | 'captain' | 'enforcer',
  superiorId?: string
): NemesisRival {
  const names = [
    'System Lord Moloc',
    'Prior Orik',
    'Centurion Xor-7',
    'Captain Ironhide',
    'Dread Marauder Zark',
    'Archon Vaelis',
    'Overseer Hathor',
    'Inquisitor Dagon',
    'Sub-Commander Tarek',
    'Warlord Valakor',
    'Baron Malakar',
    'Sovereign Seth',
  ];
  const titles = [
    'The Blood Scourge',
    'Naquadah Devourer',
    'Star Destroyer',
    'Cybernetic Abomination',
    'The Undying',
    'Flame of the Ori',
    'Void Stalker',
    'The Iron Reaver',
    'The Silent Executioner',
    'The Dread Architect',
  ];
  const races = [
    'Goa\'uld System Lord',
    'Replicator Collective',
    'Ori Crusade',
    'Rogue Asgard Faction',
    'Mercenary Void Syndicate',
    'Kull Warrior Hybrid',
    'Lucian Alliance Veteran',
  ];
  const avatars = ['👑', '🤖', '☸️', '☠️', '🗡️', '👽', '⚓', '🔰', '🪓', '👤', '💥', '⚡'];
  const colors = ['#ef4444', '#f59e0b', '#8b5cf6', '#3b82f6', '#10b981', '#06b6d4', '#ec4899', '#f97316'];
  const sectors = [
    'Tartarus Asteroid Belt',
    'Dakara Fortress Orbit',
    'Delmak Orbital Yards',
    'Kallium Nebula Deep Space',
    'Chulak High Bastion',
    'Netu Molten Sector',
    'Othala Ghost Ring',
    'Vorash Sub-Corridor',
  ];
  const shipClasses = [
    'Dreadnought Heavy Flagship',
    'Nanite Swarm Carrier',
    'Stealth Raider Corvette',
    'Holy Crusader Battlecruiser',
    'Al\'kesh Gunship Armada',
    'Ha\'tak War Fortress',
  ];

  const randName = names[Math.floor(Math.random() * names.length)] + ' ' + Math.floor(Math.random() * 99 + 1);
  const randTitle = titles[Math.floor(Math.random() * titles.length)];
  const randRace = races[Math.floor(Math.random() * races.length)];
  const randAvatar = avatars[Math.floor(Math.random() * avatars.length)];
  const randColor = colors[Math.floor(Math.random() * colors.length)];
  const randSector = sectors[Math.floor(Math.random() * sectors.length)];
  const randShip = shipClasses[Math.floor(Math.random() * shipClasses.length)];

  let baseLevel = 15;
  let basePower = 3000;
  if (rankTier === 'overlord') {
    baseLevel = 60 + Math.floor(Math.random() * 10);
    basePower = 18000 + Math.floor(Math.random() * 5000);
  } else if (rankTier === 'warlord') {
    baseLevel = 42 + Math.floor(Math.random() * 12);
    basePower = 11000 + Math.floor(Math.random() * 4000);
  } else if (rankTier === 'captain') {
    baseLevel = 28 + Math.floor(Math.random() * 10);
    basePower = 6500 + Math.floor(Math.random() * 3000);
  } else {
    baseLevel = 15 + Math.floor(Math.random() * 10);
    basePower = 3000 + Math.floor(Math.random() * 2000);
  }

  const strength = NEMESIS_STRENGTHS_POOL[Math.floor(Math.random() * NEMESIS_STRENGTHS_POOL.length)];
  const weakness = NEMESIS_WEAKNESSES_POOL[Math.floor(Math.random() * NEMESIS_WEAKNESSES_POOL.length)];

  return {
    id: `nemesis-gen-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`,
    name: randName,
    title: randTitle,
    race: randRace,
    rankTier,
    hierarchyPosition: position,
    level: baseLevel,
    power: basePower,
    health: 100,
    maxHealth: 100,
    avatar: randAvatar,
    color: randColor,
    strengths: [strength],
    weaknesses: [weakness],
    personality: 'Hostile & Opportunistic',
    taunts: {
      greeting: `You cross the paths of ${randName}! Prepare for annihilation!`,
      defeatPlayer: 'Another foolish commander crushed under my heels!',
      retreat: 'Tactical warp jump engaged! I will crush you next time!',
      death: 'No... my legacy cannot end like this...',
    },
    history: [
      {
        id: `mem-${Date.now()}`,
        timestamp: 'Just Now',
        eventType: 'promoted',
        text: `Seized power and emerged as the new ${rankTier.toUpperCase()} in ${randSector}!`,
        powerImpact: 1000,
      },
    ],
    cyberneticsScars: [],
    vassalOfPlayer: false,
    bounty: {
      active: true,
      rewardNaquadah: basePower * 250,
      rewardMetal: basePower * 120,
      rewardGlory: Math.floor(baseLevel * 15),
      rewardDarkMatter: Math.floor(baseLevel * 5),
    },
    killsOnPlayer: 0,
    deathsToPlayer: 0,
    lastEncounterAt: 'Never',
    superiorId,
    bodyguardIds: [],
    sectorTerritory: randSector,
    shipClass: randShip,
    deranged: false,
    grudgeLevel: Math.floor(Math.random() * 30 + 10),
    vassalRole: 'none',
    vassalTributeAccumulated: { naquadah: 0, metal: 0, darkMatter: 0 },
    fleetComposition: {
      flagship: randShip,
      escorts: Math.floor(baseLevel / 3),
      fighters: baseLevel * 3,
    },
  };
}
