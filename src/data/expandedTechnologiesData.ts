// Generator function creating all 360 technologies (90 per class)
export function generateExpandedTechnologies(): Technology[] {
  const result: Technology[] = [];

  for (const classDef of TECH_CLASSES_CONFIG) {
    const { category, subClasses } = classDef;

    subClasses.forEach((subClass, subClassIdx) => {
      for (let tierIdx = 0; tierIdx < 10; tierIdx++) {
        const tier = tierIdx + 1;
        const tierTitle = TIER_TITLES[tierIdx];
        const techType = subClass.techTypes[tierIdx % subClass.techTypes.length];
        const subType = subClass.subTypes[tierIdx % subClass.subTypes.length];
        const name = subClass.tierNames[tierIdx];
        const description = subClass.descriptions[tierIdx];
        const maxLevel = TIER_MAX_LEVELS[tierIdx];

        // Cost scaling with tier
        const baseCost = Math.round(
          TIER_BASE_COSTS[tierIdx] * (1 + (subClassIdx % 3) * 0.1)
        );
        const costGrowth = +(1.22 + tier * 0.02).toFixed(2);

        // Initial level: 1 for Tier 1 starter techs, 0 for higher tiers
        const initialLevel = tier === 1 && subClassIdx < 2 ? 1 : 0;

        // Primary Stat calculation
        const primaryStatBase = (tier * 180 + subClassIdx * 45) * (category === 'offense' ? 1.5 : 1.2);
        const primaryStat = {
          name: subClass.primaryStatName,
          value: Math.round(primaryStatBase),
          unit: subClass.primaryUnit,
        };

        // Sub-Stats calculation
        const subStats = subClass.subStatTemplates.map((tmpl) => ({
          name: tmpl.name,
          value: +(tmpl.base + tier * tmpl.step).toFixed(1),
          unit: tmpl.unit,
        }));

        const id = `tech-${category}-s${subClassIdx + 1}-t${tier}`;
        const key = `tech_${category}_${subClass.name.toLowerCase().replace(/[^a-z0-9]/g, '_')}_t${tier}`;

        result.push({
          id,
          key,
          name,
          category,
          subClass: subClass.name,
          techType,
          subType,
          tier,
          tierTitle,
          baseCost,
          costGrowth,
          level: initialLevel,
          maxLevel,
          description,
          stats: {
            primaryStat,
            subStats,
          },
          effectsSummary: `Increases ${category} combat multiplier by +15% per level. Grants ${primaryStat.name} +${primaryStat.value} ${primaryStat.unit}.`,
          powerRating: tier * 120 + 50,
          doctrineBonus: `${subClass.name} Mastery: Level scale +${tier * 2}% efficiency`,
        });
      }
    });
  }

  return result;
}

export const EXPANDED_TECHNOLOGIES: Technology[] = generateExpandedTechnologies();
