export type BlueprintCategory =
  | 'Resource Extraction'
  | 'Energy & Power'
  | 'Storage & Logistics'
  | 'Military & Defense'
  | 'Shipyard & Orbital'
  | 'Research & Science'
  | 'Housing & Population'
  | 'Government & Administration'
  | 'Terraforming & Special';

export interface StructureBlueprint {
  id: string;
  name: string;
  category: BlueprintCategory;
  subCategory: string;
  type: string;
  subType: string;
  tier: number;
  icon: string;
  description: string;
  cost: {
    metal: number;
    crystal: number;
    deuterium: number;
    naquadah: number;
    credits: number;
  };
  fieldsConsumed: number;
  buildTurns: number;
  requiredYardLevel: number;
  applicableTarget: 'planet' | 'moon' | 'both';
  stats: {
    productionBonusPct?: number;
    defenseRating?: number;
    storageCapacity?: number;
    energyOutput?: number;
    populationCapacity?: number;
    researchPointsPerTurn?: number;
  };
}

